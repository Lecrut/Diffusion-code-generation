def multiply_two_numbers(a, b):
    return a * b
if __name__ == '__main__':
    result1 = multiply_two_numbers(5, 4)
    print(f"5 * 4 = {result1}")
    result2 = multiply_two_numbers(10.5, 2)
    print(f"10.5 * 2 = {result2}")
    result3 = multiply_two_numbers(-3, 7)
    print(f"-3 * 7 = {result3}")