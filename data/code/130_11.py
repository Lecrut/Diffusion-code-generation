def check_number(number):
    if number == 0:
        print("The number is zero.")
    else:
        print("The number is not zero.")
if __name__ == '__main__':
    sample_value = 0
    check_number(sample_value)
    sample_value = 5
    check_number(sample_value)
    sample_value = -10
    check_number(sample_value)