add = lambda x, y: x + y
sub = lambda x, y: x - y
mul = lambda x, y: x * y
div = lambda x, y: x / y

if __name__ == '__main__':
    num1 = 5
    num2 = 3
    print("Addition:", add(num1, num2))
    print("Subtraction:", sub(num1, num2))
    print("Multiplication:", mul(num1, num2))
    print("Division:", div(num1, num2))