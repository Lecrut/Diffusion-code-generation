def calculate_product(a, b):
    return a * b
if __name__ == '__main__':
    result1 = calculate_product(5, 4)
    print(f"5 * 4 = {result1}")
    result2 = calculate_product(3.5, 2)
    print(f"3.5 * 2 = {result2}")
    result3 = calculate_product(-10, 3)
    print(f"-10 * 3 = {result3}")
    result4 = calculate_product(1.5, 2.5)
    print(f"1.5 * 2.5 = {result4}")