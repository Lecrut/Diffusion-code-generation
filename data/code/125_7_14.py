def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

if __name__ == '__main__':
    sample_a = 7
    sample_b = 2
    result_add = add(sample_a, sample_b)
    result_subtract = subtract(sample_a, sample_b)
    print("Addition Result:", result_add)
    print("Subtraction Result:", result_subtract)