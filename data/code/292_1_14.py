def calculate_perimeter(side_length):
    return 4 * side_length

if __name__ == '__main__':
    sample_side1 = 3
    perimeter1 = calculate_perimeter(sample_side1)
    print(f"Perimeter for side length {sample_side1}: {perimeter1}")
    
    sample_side2 = 10
    perimeter2 = calculate_perimeter(sample_side2)
    print(f"Perimeter for side length {sample_side2}: {perimeter2}")