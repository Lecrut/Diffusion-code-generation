def subtract(a, b):
    return a - b

if __name__ == '__main__':
    result1 = subtract(15, 6)
    print(f"15 - 6 = {result1}")
    result2 = subtract(8, 3)
    print(f"8 - 3 = {result2}")
    result3 = subtract(-7, -4)
    print(f"-7 - (-4) = {result3}")
    result4 = subtract(-20, 5)
    print(f"-20 - 5 = {result4}")