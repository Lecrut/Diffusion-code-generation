class MiddleLocator:
    def __init__(self, data):
        self.data = data
        self.length = len(data)

    def get_odd_middle(self):
        idx = self.length // 2
        return self.data[idx]

    def get_even_middle(self):
        idx = self.length // 2
        return self.data[idx]

    def locate_middle(self):
        if self.length == 0:
            return None
        if self.length % 2 == 1:
            return self.get_odd_middle()
        return self.get_even_middle()

