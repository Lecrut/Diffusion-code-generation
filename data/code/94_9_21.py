def check_any_true(iterable):
    if not hasattr(iterable, '__iter__'):
        raise ValueError("Input must be an iterable")
    if hasattr(iterable, '__len__') and len(iterable) == 0:
        return False
    iterator = iter(iterable)
    while True:
        try:
            item = next(iterator)
            if item:
                return True
        except StopIteration:
            return False

