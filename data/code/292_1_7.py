def calculate_perimeter(side_length):
    return 4 * side_length

if __name__ == '__main__':
    sample_side_length1 = 3
    result1 = calculate_perimeter(sample_side_length1)
    print(f"Perimeter for {sample_side_length1}: {result1}")
    
    sample_side_length2 = 5
    result2 = calculate_perimeter(sample_side_length2)
    print(f"Perimeter for {sample_side_length2}: {result2}")
    
    sample_side_length3 = 10
    result3 = calculate_perimeter(sample_side_length3)
    print(f"Perimeter for {sample_side_length3}: {result3}")