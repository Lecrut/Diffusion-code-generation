def generate_truth_table(a, b):
    print(f"a: {a}, b: {b}")
    print("--------------------")
    print("a | b | a AND b | a OR b | NOT a")
    print("---|---|---------|--------|-------")
    print(f"{'True'}| {'True'}| {a and b} | {a or b} | {not a}")
    print(f"{'True'}| {'False'}| {a and not b} | {a or not b} | {not a}")
    print(f"{'False'}| {'True'}| {not a and b} | {not a or b} | {not (not a)}")
    print(f"{'False'}| {'False'}| {not a and not b} | {not a or not b} | {not (not a)}")
if __name__ == '__main__':
    generate_truth_table(True, True)
    print("\n" + "="*20 + "\n")
    generate_truth_table(True, False)
    print("\n" + "="*20 + "\n")
    generate_truth_table(False, True)
    print("\n" + "="*20 + "\n")
    generate_truth_table(False, False)