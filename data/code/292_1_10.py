def calculate_perimeter(side_length):
    return 4 * side_length

if __name__ == '__main__':
    side_length1 = 3
    perimeter1 = calculate_perimeter(side_length1)
    print(f"Perimeter for side length {side_length1}: {perimeter1}")
    
    side_length2 = 5
    perimeter2 = calculate_perimeter(side_length2)
    print(f"Perimeter for side length {side_length2}: {perimeter2}")