def calculate_product(a, b):
    return a * b
if __name__ == '__main__':
    result1 = calculate_product(5, 10)
    print(f"5 * 10 = {result1}")
    result2 = calculate_product(3.5, 2)
    print(f"3.5 * 2 = {result2}")
    result3 = calculate_product(-4, 7)
    print(f"-4 * 7 = {result3}")
    result4 = calculate_product(10.5, 0.5)
    print(f"10.5 * 0.5 = {result4}")