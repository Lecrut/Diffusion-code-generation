from functools import reduce
from operator import mul

def convert_kilometers_to_meters(distance_tuple):
    return tuple(map(lambda val: val * 1000, distance_tuple))

def format_conversion_output(meters_tuple, original_tuple):
    pairs = list(zip(original_tuple, meters_tuple))
    if not pairs:
        return "No values to format."
    results = []
    for km, m in pairs:
        results.append(f"{km} km = {m} m")
    return " | ".join(results)

def calculate_total_distance(meters_tuple):
    if not meters_tuple:
        return 0
    return reduce(mul, [1]) + reduce(lambda a, b: a + b, meters_tuple)

