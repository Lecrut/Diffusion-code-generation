def sort_names(names):
    return sorted(names)
if __name__ == '__main__':
    names1 = ["Alice", "bob", "Charlie", "david"]
    sorted_names1 = sort_names(names1)
    print(sorted_names1)
    names2 = ["Zoe", "alex", "Beth", "carl"]
    sorted_names2 = sort_names(names2)
    print(sorted_names2)
    names3 = ["Apple", "banana", "Cherry", "date"]
    sorted_names3 = sort_names(names3)
    print(sorted_names3)