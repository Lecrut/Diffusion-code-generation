def generate_truth_table(a, b):
    print(f"a: {a}, b: {b}")
    print("--------------------")
    print(f"a=True, b=True, a AND b = {a and b}")
    print(f"a=True, b=False, a AND b = {a and not b}")
    print(f"a=False, b=True, a AND b = {not a and b}")
    print(f"a=False, b=False, a AND b = {not a and not b}")
if __name__ == '__main__':
    generate_truth_table(True, True)
    print("\n" + "="*20 + "\n")
    generate_truth_table(True, False)
    print("\n" + "="*20 + "\n")
    generate_truth_table(False, True)
    print("\n" + "="*20 + "\n")
    generate_truth_table(False, False)