def calculate_sum_difference():
    num1 = 15
    num2 = 7
    sum_result = num1 + num2
    difference_result = num1 - num2
    print(f"The first number is: {num1}")
    print(f"The second number is: {num2}")
    print(f"The sum of the two numbers is: {sum_result}")
    print(f"The difference between the two numbers is: {difference_result}")
if __name__ == '__main__':
    calculate_sum_difference()