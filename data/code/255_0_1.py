def find_maximum(numbers):
    return max(numbers)
if __name__ == '__main__':
    data1 = [10, 5, 20, 8]
    result1 = find_maximum(data1)
    print(result1)
    data2 = [-5, -1, -10, -3]
    result2 = find_maximum(data2)
    print(result2)
    data3 = [3.14, 2.71, 1.618]
    result3 = find_maximum(data3)
    print(result3)