def merge_strings(s1: str, s2: str) -> None:
    it1 = iter(s1)
    it2 = iter(s2)
    while True:
        try:
            char1 = next(it1)
            yield char1
            if not any(map(lambda x: ord(x), [it2])) or (len(s2) == 0):
                break
        except StopIteration:
            pass                 
