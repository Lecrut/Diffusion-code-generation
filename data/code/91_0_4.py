def negate_boolean():
    a = True
    b = False
    result_a = not a
    result_b = not b
    print(f"Original value of a: {a}")
    print(f"Negated value of a (not a): {result_a}")
    print(f"Original value of b: {b}")
    print(f"Negated value of b (not b): {result_b}")
if __name__ == '__main__':
    negate_boolean()