def generate_truth_table(a, b):
    print(f"a: {a}, b: {b}")
    print("--------------------")
    print(f"a=True, b=True: True, True")
    print(f"a=True, b=False: True, False")
    print(f"a=False, b=True: False, True")
    print(f"a=False, b=False: False, False")
if __name__ == '__main__':
    generate_truth_table(True, True)
    print("\n" * 2)
    generate_truth_table(True, False)
    print("\n" * 2)
    generate_truth_table(False, True)
    print("\n" * 2)
    generate_truth_table(False, False)