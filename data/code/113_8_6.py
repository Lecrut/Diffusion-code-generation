def subtract(a, b):
    return a - b

if __name__ == '__main__':
    result1 = subtract(20, 8)
    print(f"20 - 8 = {result1}")
    result2 = subtract(7, 3)
    print(f"7 - 3 = {result2}")
    result3 = subtract(-4, -9)
    print(f"-4 - (-9) = {result3}")
    result4 = subtract(0, 0)
    print(f"0 - 0 = {result4}")