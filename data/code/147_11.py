def sort_list(input_list):
    return sorted(input_list)
if __name__ == '__main__':
    sample1 = [5, 2, 8, 1, 9]
    result1 = sort_list(sample1)
    print(result1)
    sample2 = [3.14, 1.618, 2.718]
    result2 = sort_list(sample2)
    print(result2)
    sample3 = ['banana', 'apple', 'cherry']
    result3 = sort_list(sample3)
    print(result3)
    sample4 = [10, 5, 10, 2]
    result4 = sort_list(sample4)
    print(result4)