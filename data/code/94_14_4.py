def is_any_true(input_bool, bool_list):
    return input_bool or any(bool_list)
if __name__ == '__main__':
    test_case_1 = (True, [False, False])
    result_1 = is_any_true(*test_case_1)
    print(f"Test Case 1: {result_1}")
    test_case_2 = (False, [False, False])
    result_2 = is_any_true(*test_case_2)
    print(f"Test Case 2: {result_2}")
    test_case_3 = (False, [True, False])
    result_3 = is_any_true(*test_case_3)
    print(f"Test Case 3: {result_3}")
    test_case_4 = (True, [True, True])
    result_4 = is_any_true(*test_case_4)
    print(f"Test Case 4: {result_4}")
    test_case_5 = (False, [])
    result_5 = is_any_true(*test_case_5)
    print(f"Test Case 5: {result_5}")