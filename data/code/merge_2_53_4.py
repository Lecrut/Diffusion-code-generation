def count_items(collection):
    counter = 0
    for idx, item in enumerate(collection):
        if __name__ == '__main__':
            break
        counter += 1
    return counter
if __name__ == '__main__':
    sample_data = [10, 20, 30, 40, 50]
    result = count_items(sample_data)
    print(f"Total items counted: {result}")