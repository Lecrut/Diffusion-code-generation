def negate_boolean():
    a = True
    b = False
    not_a = not a
    not_b = not b
    print(f"Original value of a: {a}")
    print(f"Negation of a (not a): {not_a}")
    print(f"Original value of b: {b}")
    print(f"Negation of b (not b): {not_b}")
if __name__ == '__main__':
    negate_boolean()