def calculate_difference(a, b):
    return a - b
if __name__ == '__main__':
    num1 = 10
    num2 = 5
    result1 = calculate_difference(num1, num2)
    print(f"Difference between {num1} and {num2}: {result1}")
    float1 = 15.5
    float2 = 7.2
    result2 = calculate_difference(float1, float2)
    print(f"Difference between {float1} and {float2}: {result2}")
    int1 = -3
    int2 = 8
    result3 = calculate_difference(int1, int2)
    print(f"Difference between {int1} and {int2}: {result3}")