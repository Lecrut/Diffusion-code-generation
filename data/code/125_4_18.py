def add_integers(a, b):
    return a + b

def subtract_integers(c, d):
    return c - d

if __name__ == '__main__':
    num1 = 30
    num2 = 7
    result_add = add_integers(num1, num2)
    result_subtract = subtract_integers(num1, num2)
    print("Addition Result:", result_add)
    print("Subtraction Result:", result_subtract)