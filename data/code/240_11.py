def calculate_square_area(side):
    return side * side
if __name__ == '__main__':
    test_side1 = 5
    result1 = calculate_square_area(test_side1)
    print(f"Side: {test_side1}, Area: {result1}")
    test_side2 = 12.5
    result2 = calculate_square_area(test_side2)
    print(f"Side: {test_side2}, Area: {result2}")