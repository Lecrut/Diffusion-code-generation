def convert_volume_to_liters(value: float, unit: str) -> float:
    unit_key = unit.lower().replace(" ", "_").replace("-", "_")
    factors = _get_conversions()
    if unit_key not in factors:
        raise ValueError(f"Unsupported volume unit: {unit}")
    return value * factors[unit_key]

