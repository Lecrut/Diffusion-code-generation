def calculate_list_sum(numbers):
    return sum(numbers)

if __name__ == '__main__':
    list1 = [2, 4, 6, 8]
    result1 = calculate_list_sum(list1)
    print(result1)
    
    list2 = [15.5, 25.0, 35.75]
    result2 = calculate_list_sum(list2)
    print(result2)
    
    list3 = [-2, -4, 6, -8]
    result3 = calculate_list_sum(list3)
    print(result3)