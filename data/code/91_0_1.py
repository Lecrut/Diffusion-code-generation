def negate_boolean():
    a = True
    b = False
    neg_a = not a
    neg_b = not b
    print(f"Original value of a: {a}")
    print(f"Negated value of a (not a): {neg_a}")
    print(f"Original value of b: {b}")
    print(f"Negated value of b (not b): {neg_b}")
if __name__ == '__main__':
    negate_boolean()