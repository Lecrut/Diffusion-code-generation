def calculate_list_sum(numbers):
    return sum(numbers)

if __name__ == '__main__':
    list_a = [10, 20, 30]
    result_a = calculate_list_sum(list_a)
    print(f'Sum of list_a: {result_a}')
    
    list_b = [5.5, 4.5, 3.5, 2.5, 1.5]
    result_b = calculate_list_sum(list_b)
    print(f'Sum of list_b: {result_b}')