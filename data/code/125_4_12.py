def add_integers(a, b):
    return a + b

def subtract_integers(c, d):
    return c - d
if __name__ == '__main__':
    sample_a = 15
    sample_b = 7
    sample_c = 20
    sample_d = 3
    addition_result = add_integers(sample_a, sample_b)
    subtraction_result = subtract_integers(sample_c, sample_d)
    print(addition_result)
    print(subtraction_result)