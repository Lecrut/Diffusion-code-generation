def subtract_values(a, b):
    return a - b

if __name__ == '__main__':
    value1 = 100
    value2 = 45
    result1 = subtract_values(value1, value2)
    print(f"Result of {value1} - {value2}: {result1}")

    value3 = 50
    value4 = 150
    result2 = subtract_values(value3, value4)
    print(f"Result of {value3} - {value4}: {result2}")