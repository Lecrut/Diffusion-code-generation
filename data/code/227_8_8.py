def print_heart_star():
    coordinates = [
        (0, 2), (1, 3), (2, 4), (3, 5), (4, 6), (5, 7), (6, 8),
        (7, 9), (8, 8), (9, 7), (10, 6), (11, 5), (12, 4), (13, 3),
        (14, 2), (13, 1), (12, 0), (11, -1), (10, -2), (9, -3),
        (8, -4), (7, -5), (6, -6), (5, -7), (4, -8), (3, -9),
        (2, -10), (1, -11), (0, -12)
    ]
    for x, y in coordinates:
        print(f"\t{'*' if y >= 0 else ' ' * abs(y)}{'* ' * (x + 1)}")

if __name__ == '__main__':
    print_heart_star()