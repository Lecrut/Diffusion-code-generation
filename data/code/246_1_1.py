def add_numbers(a, b):
    return a + b
if __name__ == '__main__':
    num1 = 15
    num2 = 7
    result = add_numbers(num1, num2)
    print(f"The sum of {num1} and {num2} is: {result}")
    num3 = -10
    num4 = 25
    result2 = add_numbers(num3, num4)
    print(f"The sum of {num3} and {num4} is: {result2}")