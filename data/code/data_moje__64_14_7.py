def calculate_power(base, exponent):
    if exponent == 0:
        if base == 0:
            return float('nan')
        return 1
    if exponent < 0:
        base = 1 / base
        exponent = -exponent
    result = 1
    current_base = base
    while exponent > 0:
        if exponent % 2 == 1:
            result *= current_base
        current_base *= current_base
        exponent //= 2
    return result

