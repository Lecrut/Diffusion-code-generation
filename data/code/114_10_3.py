def multiply_two_numbers(a, b):
    return a * b
if __name__ == '__main__':
    result1 = multiply_two_numbers(5, 4)
    print(f"The product of 5 and 4 is: {result1}")
    result2 = multiply_two_numbers(10.5, 2)
    print(f"The product of 10.5 and 2 is: {result2}")
    result3 = multiply_two_numbers(-3, 7)
    print(f"The product of -3 and 7 is: {result3}")