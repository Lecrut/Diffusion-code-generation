def main():
    """
    Demonstrates string concatenation with sample data.
    Since user input is prohibited, this function uses hard-coded values.
    """
    str_one = "Hello"
    str_two = ", World!"
    
    # Combine the two strings and print the result
    combined_result = str_one + " " + str_two
    
    print(combined_result)

if __name__ == '__main__':
    main()