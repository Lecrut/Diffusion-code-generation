def calculator():
    a = 10
    b = 5
    sum_result = a + b
    difference_result = a - b
    product_result = a * b
    quotient_result = a / b
    print(f"Number A: {a}")
    print(f"Number B: {b}")
    print(f"Addition (A + B): {sum_result}")
    print(f"Subtraction (A - B): {difference_result}")
    print(f"Multiplication (A * B): {product_result}")
    print(f"Division (A / B): {quotient_result}")
if __name__ == '__main__':
    calculator()